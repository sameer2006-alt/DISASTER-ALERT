export function getStateCoordinates(stateName) {
  if (!stateName) return null
  return STATE_COORDINATES[stateName] || null
}

/**
 * Returns city centroid coordinates
 */
export function getCityCoordinates(cityName) {
  if (!cityName) return null
  const normalized = cityName.toLowerCase().trim()
  if (CITY_COORDINATES[normalized]) {
    return CITY_COORDINATES[normalized]
  }
  // Try partial match for combined names like "mohali" in "mohali (sas nagar)"
  for (const [key, coords] of Object.entries(CITY_COORDINATES)) {
    if (key.includes(normalized) || normalized.includes(key)) {
      return coords
    }
  }
  return null
}

/**
 * Resolves best available coordinates for a state + city pair.
 * Returns { latitude, longitude, isApproximate } or null.
 */
export function getLocationCoordinates(stateName, cityName) {
  const cityCoords = getCityCoordinates(cityName)
  if (cityCoords) {
    return { ...cityCoords, isApproximate: false }
  }
  const stateCoords = getStateCoordinates(stateName)
  if (stateCoords) {
    return { ...stateCoords, isApproximate: true }
  }
  return null
}
